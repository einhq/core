/**
 * Write each module's `deno.jsonc` from its `mod.json`.
 *
 * A module is a Deno workspace member (`"workspace": ["./modules/*"]` in core's `deno.jsonc`), so
 * the files under `modules/<name>/` resolve their bare specifiers against `modules/<name>/deno.jsonc`
 * first and core's map only after. That is what lets core stop carrying `@archive/media/*`, `@archive/people/*`
 * and the rest: they belong to the module that declares them, and the module already
 * declares them — `mod.json` is what `ts-command-loader.ts` resolves a bin against at runtime.
 *
 * The member config is generated rather than written by hand because two hand-maintained copies of
 * the same import map is precisely the duplication being removed. `mod.json` is the source; this
 * script is the projection; `src/modules/test/module-boundary.test.ts` fails the fast tier if the
 * two drift. The projection is `moduleImportMap` (`src/modules/resolve.ts`): the module's own
 * `imports`, its own `exports` as `@<name>/…`, and each dependency's `exports` as `@<dep>/…` —
 * the same rule the loader applies at runtime, so a file type-checks against exactly what it may
 * import. `ui-build` scopes route sources with this file for the same reason.
 *
 * A module with pages (`ui.routes`) also gets what the shell lends them — React, Mantine and the
 * kit as `@ein/ui/*` (`lentTypePaths`) — so its page sources type-check; they are bundled by
 * `ui-build` against the running shell, so nothing at runtime reads these entries.
 *
 * A member map is *additive* — it does not replace core's. That is the whole reason this works
 * where a generated standalone import map did not: `@ein/client`, `pg` and `ssh2` still resolve
 * through the root map exactly as before, so none of their types are re-resolved.
 *
 * Usage: deno run -A scripts/sync-module-configs.ts [--check] [modules-dir]
 */

import { fromFileUrl, join, relative, resolve } from '@std/path';
import { parse } from '@std/jsonc';
import { moduleImportMap } from '../src/modules/resolve.ts';
import type { ModuleManifest } from '../src/modules/types.ts';
import { lentTypePaths } from '../src/builtin/ui/lib/shared.ts';
import { moduleSourceDir, repoModules, UI_SOURCE_DIR } from '../src/modules/repo.ts';

const HEADER = [
  "// Generated by `deno task sync:modules` from this module's mod.json. Do not edit.",
  '//',
  '// This module is a Deno workspace member, so everything under it type-checks and runs against',
  "// its own manifest rather than against core's import map: its own imports and exports, and the",
  '// exports of the modules it lists in dependencies. Change mod.json and re-run the task.',
].join('\n');

const args = Deno.args.filter((arg) => arg !== '--check');
const checkOnly = Deno.args.includes('--check');

const repoRoot = fromFileUrl(new URL('..', import.meta.url));
/** The modules to sync: those under a directory given, or every module in the checkout. */
const moduleDirs = (): { name: string; dir: string }[] => {
  if (!args[0]) return repoModules();
  const dir = resolve(args[0]);
  return [...Deno.readDirSync(dir)].filter((entry) => entry.isDirectory || entry.isSymlink).map((entry) => ({ name: entry.name, dir: join(dir, entry.name) }));
};

/** What `modules/<name>/deno.jsonc` should contain, or undefined when the module needs no config. */
export const memberConfigFor = (imports: Record<string, string>): string | undefined => {
  const keys = Object.keys(imports).sort();
  if (keys.length === 0) return undefined;

  const body = keys.map((key) => `    ${JSON.stringify(key)}: ${JSON.stringify(imports[key])}`).join(',\n');
  return `${HEADER}\n{\n  "imports": {\n${body}\n  }\n}\n`;
};

/** Where a module's root finds the shell's kit sources: the shell's client directory. */
const kitDirFrom = (moduleRoot: string): string => relative(moduleRoot, join(UI_SOURCE_DIR, 'src', 'client'));

/** Core's import map, `deno.jsonc` `imports`: the versions of the packages the shell lends. */
const coreImports = (parse(await Deno.readTextFile(join(repoRoot, 'deno.jsonc'))) as { imports: Record<string, string> }).imports;

/** A module's member map: the module rule, plus what the shell lends when it has pages. */
export const memberImportsFor = (manifest: ModuleManifest, manifests: Map<string, ModuleManifest>): Record<string, string> => ({
  ...(manifest.ui?.routes ? lentTypePaths(coreImports, kitDirFrom(moduleSourceDir(manifest.name))) : {}),
  ...moduleImportMap(manifest, (dep) => manifests.get(dep)),
});

/** Every manifest, by module name, with the directory it is in. */
const readHostManifests = async (): Promise<{ manifests: Map<string, ModuleManifest>; dirs: Map<string, string> }> => {
  const manifests = new Map<string, ModuleManifest>();
  const dirs = new Map<string, string>();
  for (const { name, dir } of moduleDirs()) {
    try {
      manifests.set(name, JSON.parse(await Deno.readTextFile(join(dir, 'mod.json'))));
      dirs.set(name, dir);
    } catch {
      // not a module
    }
  }
  return { manifests, dirs };
};

const changed: string[] = [];
const { manifests, dirs } = await readHostManifests();

for (const [name, manifest] of manifests) {
  const moduleRoot = dirs.get(name)!;
  const configPath = join(moduleRoot, 'deno.jsonc');
  const wanted = memberConfigFor(memberImportsFor(manifest, manifests));

  let current: string | undefined;
  try {
    current = await Deno.readTextFile(configPath);
  } catch {
    current = undefined;
  }

  // Compare the parsed maps, not the text: a config someone reformatted is not drift, and saying
  // it is would make the check fail for a reason it cannot explain.
  const sameMap = current !== undefined && wanted !== undefined &&
    JSON.stringify((parse(current) as { imports?: Record<string, string> }).imports ?? {}) ===
      JSON.stringify((parse(wanted) as { imports?: Record<string, string> }).imports ?? {});
  if (current === wanted || sameMap) continue;

  changed.push(relative(repoRoot, configPath));
  if (checkOnly) continue;

  if (wanted === undefined) await Deno.remove(configPath);
  else await Deno.writeTextFile(configPath, wanted);
}

if (changed.length === 0) {
  console.log('module configs are in sync');
} else if (checkOnly) {
  console.error(`out of sync with mod.json, run \`deno task sync:modules\`:\n  ${changed.join('\n  ')}`);
  Deno.exit(1);
} else {
  console.log(`wrote ${changed.length}:\n  ${changed.join('\n  ')}`);
}
